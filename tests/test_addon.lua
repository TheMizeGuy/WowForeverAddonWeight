    T.eq(life.loaded, true)
    T.eq(life.level, 2)
    T.eq((ns.ShortReason(life)), "2.00 ms a frame")
    T.eq(ns.db.totals.sessions, 2)
    Near(ns.Average(ns.addons.Alpha), 3, 0.001, "the session's own figures are untouched")
end)


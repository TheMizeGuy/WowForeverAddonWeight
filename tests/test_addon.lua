    wow.Start({ addons = Three() })
    _G.AddonWeightDB.stats = { Alpha = { n = "many", sum = 4, title = 7, removed = "yes" }, Bravo = "x", [5] = {} }
    _G.AddonWeightDB.totals = "lots"

T.test("what each addon cost is saved at logout and added to at the next session", function()
    local ns = Settled({ setup = function()
        wow.memoryLive.Alpha = 4096
        wow.Metric("Alpha", "RecentAverageTime", 1)
    end })
    wow.Run(15)
    wow.Metric("Alpha", "CountTimeOver50Ms", 3)
    wow.Metric("Alpha", "PeakTime", 80)
    wow.Metric("Alpha", "LastTime", 150)
    Stutter(0.2)
    local first = ns.addons.Alpha.n
    T.ok(first >= 15 and first <= 17, tostring(first))
    wow.Fire("PLAYER_LOGOUT")
    local stats = _G.AddonWeightDB.stats.Alpha
    T.eq(stats.n, first)
    Near(stats.sum, first)
    T.eq(stats.hitches, 3)
    T.eq(stats.stutters, 1)
    T.eq(stats.peak, 80)
    T.eq(stats.mem, 4096)
    T.eq(stats.sessions, 1)
    T.ok(stats.seconds > 15 and stats.seconds < 17, tostring(stats.seconds))
    T.eq(_G.AddonWeightDB.totals.sessions, 1)
    T.eq(#_G.AddonWeightDB.stutterLog, 1)

    ns = wow.Start({ addons = Three(), keepDB = true, reload = true, setup = function() wow.Metric("Alpha", "RecentAverageTime", 3) end })
